/* Insert what is missing. Matched on name AND code, because Office Ally issues
   one code to two payers (ALLCA) and the same name can carry two codes. */
INSERT INTO dbo.DmePayers (Name, PayerCode)
SELECT c.Name, c.PayerCode
FROM #Catalog c
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.DmePayers p
    WHERE p.Name = c.Name AND p.PayerCode = c.PayerCode);

PRINT 'Payers inserted: ' + CAST(@@ROWCOUNT AS VARCHAR(10));

/* Remove anything that is not the vendor's. On a repository-built database
   these are the four demo rows and nothing else. */
DELETE p
FROM dbo.DmePayers p
WHERE NOT EXISTS (
    SELECT 1 FROM #Catalog c
    WHERE c.Name = p.Name AND c.PayerCode = p.PayerCode);

PRINT 'Non-catalog payers removed: ' + CAST(@@ROWCOUNT AS VARCHAR(10));

DROP TABLE #Catalog;
GO

/* ---------------------------------------------------------------------------
   5. Indexes

   Name drives the typeahead. PayerCode is NOT unique: see the ALLCA note in
   the header. A unique index here would reject Office Ally's own list.
   --------------------------------------------------------------------------- */
IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE object_id = OBJECT_ID('dbo.DmePayers') AND name = 'IX_DmePayers_Name')
    CREATE INDEX IX_DmePayers_Name ON dbo.DmePayers (Name) INCLUDE (PayerCode);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE object_id = OBJECT_ID('dbo.DmePayers') AND name = 'IX_DmePayers_PayerCode')
    CREATE INDEX IX_DmePayers_PayerCode ON dbo.DmePayers (PayerCode) INCLUDE (Name);
GO

/* ---------------------------------------------------------------------------
   Verification
   --------------------------------------------------------------------------- */
SELECT 'payers'            AS Item, COUNT(*) AS Value FROM dbo.DmePayers
UNION ALL
SELECT 'tenant scoped',    COUNT(*) FROM sys.columns
    WHERE object_id = OBJECT_ID('dbo.DmePayers') AND name = 'TenantId'
UNION ALL
SELECT 'in RLS policy',    COUNT(*) FROM sys.security_predicates
    WHERE target_object_id = OBJECT_ID('dbo.DmePayers')
UNION ALL
SELECT 'duplicate codes',  COUNT(*) FROM (
    SELECT PayerCode FROM dbo.DmePayers GROUP BY PayerCode HAVING COUNT(*) > 1) d;
GO
