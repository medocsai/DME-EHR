/* =============================================================================
   DME — Payer catalog: the Office Ally national list
   Date: 2026-08-27
   Migration order: 10 (after 2026-08-26_DME_User_Locations.sql)

   WHY
   ---
   The client's words: "List of insurance is not exhaustive." The payer dropdown
   on the customer form offered FOUR payers, seeded as demo data in
   2026-06-19_DME_Core_Schema.sql. A supplier could not bill anyone else, and
   there was no screen to add one, so they could not fix it themselves either.

   Office Ally, the clearinghouse this product submits through, publishes the
   list of payers it can reach, with the Payer ID that addresses each one. That
   list is 4,017 payers and it is loaded here.

   WHY THE TABLE STOPS BEING TENANT DATA
   -------------------------------------
   DmePayers was tenant scoped and inside TenantIsolationPolicy, and
   DME_Onboard_New_Tenant.sql copied the four rows into every new supplier.
   Copying a NATIONAL list into every tenant is 4,017 duplicates per supplier of
   a list none of them owns, and they drift the first time one copy is corrected.
   It becomes a global reference table, exactly like DmeCarcCodes: one row per
   payer, no TenantId, out of the security policy, and a new tenant gets it free.

   Nothing is lost by that. The payer a customer is actually insured with is a
   TENANT fact and it already lives in DmeCustomerInsurances, which stores
   PayerName and PayerId as text with no foreign key. That is deliberate and
   stays: it is the point-in-time record of what the claim was billed under, and
   it must not change if the catalog is later corrected.

   WHY THERE IS NO "ADD YOUR OWN PAYER" BUTTON
   -------------------------------------------
   A payer that is not on the Office Ally list has no Payer ID, so an 837 cannot
   be addressed to it. Letting a supplier type a new payer would produce a record
   that looks billable and is not, and the failure would surface weeks later as a
   rejected claim. A genuinely missing payer is added to this catalog centrally,
   which is the same path an Office Ally list refresh takes anyway.

   PayerType IS DROPPED
   --------------------
   Nothing in the codebase ever read it, and the Office Ally export has no
   equivalent. CMS-1500 box 1 (Medicare / Medicaid / Tricare / group health) is
   not implemented on the claim form at all, so the column was not feeding that
   either. If box 1 is built later it needs a real answer, not this column.

   DUPLICATE PAYER IDs ARE REAL
   ----------------------------
   Office Ally issues the code ALLCA to two different payer names. PayerCode is
   therefore INDEXED BUT NOT UNIQUE. A unique constraint here would reject the
   vendor's own data.

   SAFE TO RE-RUN. The catalog load is a set difference, and every schema change
   is guarded. ALTER SECURITY POLICY and any batch naming a dropped column are
   validated at COMPILE time, so IF NOT EXISTS does not protect them: those are
   driven through sp_executesql.
   ============================================================================= */

SET NOCOUNT ON;
GO

/* ---------------------------------------------------------------------------
   1. Take DmePayers out of the row level security policy

   It has to come out BEFORE TenantId is dropped: the predicate is defined on
   that column, and the ALTER TABLE fails while the policy depends on it.
   --------------------------------------------------------------------------- */
IF EXISTS (
    SELECT 1 FROM sys.security_predicates sp
    JOIN sys.security_policies p ON p.object_id = sp.object_id
    WHERE p.name = 'TenantIsolationPolicy'
      AND sp.target_object_id = OBJECT_ID('dbo.DmePayers'))
BEGIN
    DECLARE @drop NVARCHAR(MAX) = N'';

    SELECT @drop = @drop +
        'ALTER SECURITY POLICY dbo.TenantIsolationPolicy DROP ' +
        sp.predicate_type_desc + ' PREDICATE ON dbo.DmePayers' +
        CASE WHEN sp.predicate_type_desc = 'BLOCK'
             THEN ' ' + sp.operation_desc ELSE '' END + ';' + CHAR(10)
    FROM sys.security_predicates sp
    JOIN sys.security_policies p ON p.object_id = sp.object_id
    WHERE p.name = 'TenantIsolationPolicy'
      AND sp.target_object_id = OBJECT_ID('dbo.DmePayers');

    EXEC sp_executesql @drop;
    PRINT 'DmePayers removed from TenantIsolationPolicy.';
END
ELSE
    PRINT 'DmePayers already outside TenantIsolationPolicy.';
GO

/* ---------------------------------------------------------------------------
   2. Drop TenantId and PayerType

   Any default constraint on them has to go first, or the ALTER is refused.
   --------------------------------------------------------------------------- */
DECLARE @col SYSNAME, @sql NVARCHAR(MAX);
DECLARE cols CURSOR LOCAL FAST_FORWARD FOR
    SELECT name FROM (VALUES ('TenantId'), ('PayerType')) AS x(name);

OPEN cols;
FETCH NEXT FROM cols INTO @col;
WHILE @@FETCH_STATUS = 0
BEGIN
    -- Cleared every iteration. A SELECT that matches no row leaves the variable
    -- HOLDING THE PREVIOUS ITERATION'S STATEMENT, which on the first run of
    -- this migration meant the second pass re-executed the first column's DROP.
    SET @sql = NULL;

    IF EXISTS (SELECT 1 FROM sys.columns
               WHERE object_id = OBJECT_ID('dbo.DmePayers') AND name = @col)
    BEGIN
        SELECT @sql = 'ALTER TABLE dbo.DmePayers DROP CONSTRAINT ' + QUOTENAME(dc.name) + ';'
        FROM sys.default_constraints dc
        JOIN sys.columns c ON c.object_id = dc.parent_object_id
                          AND c.column_id = dc.parent_column_id
        WHERE dc.parent_object_id = OBJECT_ID('dbo.DmePayers') AND c.name = @col;

        IF @sql IS NOT NULL BEGIN EXEC sp_executesql @sql; SET @sql = NULL; END

        -- Indexes on the column block the drop too.
        DECLARE @ix NVARCHAR(MAX) = N'';
        SELECT @ix = @ix + 'DROP INDEX ' + QUOTENAME(i.name) + ' ON dbo.DmePayers;' + CHAR(10)
        FROM sys.indexes i
        JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id
        JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
        WHERE i.object_id = OBJECT_ID('dbo.DmePayers') AND c.name = @col AND i.is_primary_key = 0;

        IF LEN(@ix) > 0 EXEC sp_executesql @ix;

        SET @sql = 'ALTER TABLE dbo.DmePayers DROP COLUMN ' + QUOTENAME(@col) + ';';
        EXEC sp_executesql @sql;
        PRINT 'DmePayers.' + @col + ' dropped.';
    END
    ELSE
        PRINT 'DmePayers.' + @col + ' already gone.';

    FETCH NEXT FROM cols INTO @col;
END
CLOSE cols; DEALLOCATE cols;
GO

/* ---------------------------------------------------------------------------
   3. Widen Name

   The seed column was NVARCHAR(120). The longest name in the Office Ally list
   is comfortably inside that, but their list grows and a truncated payer name
   is a claim addressed to the wrong place. 200 matches what RehabDox stores.
   --------------------------------------------------------------------------- */
IF EXISTS (SELECT 1 FROM sys.columns
           WHERE object_id = OBJECT_ID('dbo.DmePayers')
             AND name = 'Name' AND max_length < 400)
BEGIN
    ALTER TABLE dbo.DmePayers ALTER COLUMN Name NVARCHAR(200) NOT NULL;
    PRINT 'DmePayers.Name widened to 200.';
END
GO

IF EXISTS (SELECT 1 FROM sys.columns
           WHERE object_id = OBJECT_ID('dbo.DmePayers')
             AND name = 'PayerCode' AND (max_length < 60 OR is_nullable = 1))
BEGIN
    UPDATE dbo.DmePayers SET PayerCode = '' WHERE PayerCode IS NULL;
    ALTER TABLE dbo.DmePayers ALTER COLUMN PayerCode NVARCHAR(30) NOT NULL;
    PRINT 'DmePayers.PayerCode tightened to NOT NULL(30).';
END
GO

